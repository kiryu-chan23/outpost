// Restyles the cburnett piece set (Colin M.L. Burnett, GPLv2+) to the Outpost
// palette and writes it as CSS data URIs. Run: npm run content:pieces
import fs from 'node:fs';
const dir = new URL('../src/assets/pieces/', import.meta.url);
const INK = '#0c1436', IVORY = '#fffaec', NAVY = '#1a2456', DETAIL = '#f3e9d2';
let css = '/* Generated by scripts/build-pieces.mjs — cburnett pieces, recoloured. */\n';
for (const color of ['white', 'black']) {
  for (const role of ['pawn', 'knight', 'bishop', 'rook', 'queen', 'king']) {
    let svg = fs.readFileSync(new URL(`${color}-${role}.orig.svg`, dir), 'utf8');
    svg = svg.replace('width="45" height="45"', 'viewBox="0 0 45 45"');
    if (color === 'white') {
      svg = svg.replaceAll('#fff', IVORY).replaceAll('#000', INK);
    } else {
      svg = svg.replace('<svg ', `<svg fill="${NAVY}" `)
        .replaceAll('#000', '\u0000').replaceAll('#ececec', DETAIL)
        .replaceAll('fill="\u0000"', `fill="${NAVY}"`).replaceAll('stroke="\u0000"', 'stroke="#060a22"');
    }
    const uri = 'data:image/svg+xml,' + encodeURIComponent(svg).replace(/%20/g, ' ').replace(/%3D/g, '=').replace(/%3A/g, ':').replace(/%2F/g, '/');
    css += `.cg-wrap piece.${role}.${color}, .piece-img.${role}.${color} { background-image: url("${uri}"); }\n`;
  }
}
fs.writeFileSync(new URL('../src/styles/pieces.css', import.meta.url), css);
console.log('pieces.css', css.length, 'bytes');
